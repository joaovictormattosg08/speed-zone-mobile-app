import { DatabaseSync } from 'node:sqlite';
import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApi } from './index.mjs';
import { listProducts, saveProduct } from './products.mjs';
test('loyalty: earnings, atomic redemption, account ownership, one-use coupons and persistence', async () => {
 const directory = await mkdtemp(join(tmpdir(), 'sz-loyalty-')); const database = join(directory, 'test.sqlite');
 let server = createApi({ database });
 const listen = () => new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
 const close = () => new Promise(resolve => server.close(resolve)); await listen();
 const call = async (path, token, body) => { const response = await fetch(`http://127.0.0.1:${server.address().port}${path}`, { method: path.startsWith('/admin/orders/') && body ? 'PATCH' : body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }); return { status: response.status, data: await response.json() }; };
 try {
  const register = email => call('/auth/register', null, { name: 'Teste', surname: 'Piloto', email, password: 'TesteSenha123!' });
  const a = (await register('a@example.com')).data.token, b = (await register('b@example.com')).data.token;
  assert.equal((await call('/loyalty')).status, 401);
  assert.equal((await call('/loyalty', a)).data.balance, 0);
  assert.equal((await call('/loyalty/redeem', a, { rewardId: 'off5', requestKey: 'empty-account' })).status, 400);
  const purchase = { items: [{ id: 'SZ-TUR-660-TS', quantity: 5 }], delivery: { cep: '01310100', service: 'express' }, requestKey: 'earn-first-points' };
  const order = await call('/orders', a, purchase); assert.equal(order.data.order.pointsEarned, 39450);
  await call('/orders', a, purchase); assert.equal((await call('/loyalty', a)).data.balance, 39450);
  const redemption = { rewardId: 'off5', requestKey: 'redeem-discount-five' };
  const results = await Promise.all([call('/loyalty/redeem', a, redemption), call('/loyalty/redeem', a, redemption)]);
  const coupon = results[0].data.coupon; assert.equal(coupon.code, results[1].data.coupon.code);
  assert.equal((await call('/loyalty', a)).data.balance, 34450);
  assert.equal((await call('/loyalty', b)).data.coupons.length, 0);
  const discounted = { ...purchase, items: [{ id: 'SZ-ACC-015', quantity: 1 }], coupon: coupon.code, requestKey: 'use-discount-five' };
  assert.equal((await call('/orders', b, discounted)).status, 400);
  assert.equal((await call('/orders', a, { ...discounted, requestKey: 'bad-checkout-rollback', checkout: {} })).status, 400);
  const applied = await call('/orders', a, discounted); assert.equal(applied.data.order.discount, 725); assert.equal(applied.data.order.pointsEarned, 137);
  assert.equal((await call('/orders', a, discounted)).data.order.id, applied.data.order.id);
  assert.equal((await call('/orders', a, { ...discounted, requestKey: 'reuse-rejected-coupon' })).status, 400);
  const shipping = (await call('/loyalty/redeem', a, { rewardId: 'shipping', requestKey: 'redeem-free-shipping' })).data.coupon;
  const free = await call('/orders', a, { ...discounted, requestKey: 'use-free-shipping', coupon: shipping.code }); assert.equal(free.data.order.shipping, 0); assert.equal(free.data.order.delivery.price, 0); assert.equal(free.data.order.pointsEarned, 145);
  for (const [rewardId, percent] of [['off10',10],['off15',15]]) { const c = (await call('/loyalty/redeem', a, { rewardId, requestKey: `redeem-${rewardId}` })).data.coupon; const o = await call('/orders', a, { ...discounted, requestKey: `use-${rewardId}`, coupon: c.code }); assert.equal(o.data.order.discount, 14500 * percent / 100); }
  const inventory = new DatabaseSync(database);
  const turbo = listProducts(inventory, true).find(p => p.id === 'SZ-TUR-660-TS');
  saveProduct(inventory, { ...turbo, stock: 5 }, turbo.id);
  inventory.close();
  await call('/orders', a, { ...purchase, requestKey: 'earn-more-points' });
  const c20 = (await call('/loyalty/redeem', a, { rewardId: 'off20', requestKey: 'redeem-twenty' })).data.coupon;
  const twenty = await call('/orders', a, { ...discounted, requestKey: 'use-twenty', coupon: c20.code }); assert.equal(twenty.data.order.discount, 2900);
  assert.equal((await call('/admin/orders', a)).status, 403);
  const access = new DatabaseSync(database); access.prepare('INSERT INTO administrators SELECT id, ? FROM users WHERE email = ?').run(new Date().toISOString(),'b@example.com'); access.close();
  assert.ok((await call('/admin/orders', b)).data.orders.length > 0);
  const endpoint = '/admin/orders/' + applied.data.order.id;
  assert.equal((await call(endpoint, a, { expectedStatus:'processing',status:'cancelled' })).status, 403);
  assert.equal((await call(endpoint, b, { expectedStatus:'processing',status:'delivered' })).status, 400);
  assert.equal((await call(endpoint, b, { expectedStatus:'processing',status:'transit' })).data.order.status, 'transit');
  assert.equal((await call(endpoint, b, { expectedStatus:'processing',status:'cancelled' })).status, 409);
  const balanceBefore = (await call('/loyalty', a)).data.balance;
  assert.equal((await call(endpoint, b, { expectedStatus:'transit',status:'cancelled' })).data.order.status, 'cancelled');
  await call(endpoint, b, { expectedStatus:'transit',status:'cancelled' });
  assert.equal((await call('/loyalty', a)).data.balance, balanceBefore - 137);
  assert.equal((await call(endpoint, b, { expectedStatus:'cancelled',status:'processing' })).status, 400);
  const customerOrder = (await call('/orders', a)).data.orders.find(item=>item.id===applied.data.order.id);
  assert.equal(customerOrder.status, 'cancelled'); assert.equal(customerOrder.statusHistory.length, 2);
  const before = (await call('/loyalty', a)).data;
  await close(); server = createApi({ database }); await listen(); assert.deepEqual((await call('/loyalty', a)).data, before);
 } finally { await close(); await rm(directory, { recursive: true, force: true }); }
});
